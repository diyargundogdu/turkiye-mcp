const normal = (s: string) => s.toLocaleLowerCase("tr-TR").normalize("NFC").trim();

export function ilBul(sorgu: string): { plaka: number; il: string }[] {
  const s = sorgu.trim();
  if (/^\d{1,2}$/.test(s)) {
    const p = Number(s);
    return p >= 1 && p <= 81 ? [{ plaka: p, il: ILLER[p - 1] }] : [];
  }
  const q = normal(s);
  return ILLER.map((il, i) => ({ plaka: i + 1, il })).filter((x) => normal(x.il).includes(q));
}
